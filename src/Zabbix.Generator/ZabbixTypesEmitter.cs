using System.Text;
using System.Xml.Linq;

namespace Community.Zabbix.Generator;

/// <summary>
/// Generates the text of <c>Community.Zabbix.types.ps1xml</c>, the module's generated, checked-in type data. Each
/// <c>role: request/nested-request/get</c> record registers <c>Zabbix.PowerShell.ZabbixRecordConverter</c> as its
/// <c>&lt;TypeConverter&gt;</c>, so a bare hashtable binds to it through PowerShell's own parameter binder; each
/// <c>role: read</c> record registers <c>Zabbix.PowerShell.ZabbixAdditionalFieldsAdapter</c> as its
/// <c>&lt;TypeAdapter&gt;</c>, so <c>$result.newfield</c> reads a wire field the record does not model.
/// </summary>
/// <remarks>A pure function of <see cref="ApiDescription"/>, called by the build-time writer
/// (<c>tools/Zabbix.PowerShell.HelpGen</c>), which reads the description text rather than reflecting over the assembly
/// the build is still writing.</remarks>
internal static class ZabbixTypesEmitter
{
    private const string Converter = "Community.Zabbix.PowerShell.ZabbixRecordConverter";
    private const string Adapter = "Community.Zabbix.PowerShell.ZabbixAdditionalFieldsAdapter";

    /// <summary>The generated <c>Community.Zabbix.types.ps1xml</c> text, LF-terminated, ending in a trailing newline.</summary>
    public static string Generate(ApiDescription description)
    {
        if (description is null) throw new ArgumentNullException(nameof(description));
        var bound = new SortedSet<string>(StringComparer.Ordinal);
        var adapted = new SortedSet<string>(StringComparer.Ordinal);
        var members = new SortedDictionary<string, List<XElement>>(StringComparer.Ordinal);
        foreach (TypeDescription type in description.Types)
        {
            string full = "Community.Zabbix." + (type.Name.StartsWith("Zabbix", StringComparison.Ordinal) ? type.Name : "Zabbix" + type.Name);
            if (type.Role is "request" or "nested-request" or "get") bound.Add(full);
            else if (type.Role == "read" && type.ExtensionData) adapted.Add(full);
            if (type.Role is "read" or "nested-read" && ShellMembers(type) is { Count: > 0 } extra) members[full] = extra;
        }
        var types = new XElement("Types",
            bound.Select(name => new XElement("Type",
                new XElement("Name", name),
                new XElement("TypeConverter", new XElement("TypeName", Converter)))),
            adapted.Select(name => new XElement("Type",
                new XElement("Name", name),
                new XElement("TypeAdapter", new XElement("TypeName", Adapter)),
                members.TryGetValue(name, out List<XElement>? extra) && members.Remove(name) ? new XElement("Members", extra) : null)),
            members.Select(entry => new XElement("Type",
                new XElement("Name", entry.Key),
                new XElement("Members", entry.Value))));
        // An explicit utf-8 XDeclaration — but XDocument.Save(TextWriter) ignores it and instead declares the
        // TextWriter's OWN .Encoding (a plain StringWriter's is UTF-16) regardless of what bytes actually reach
        // disk: the declaration stays "utf-16" even with the XDeclaration below unless the writer overrides .Encoding.
        // The writer here (ZabbixWriteTypesPs1XmlTask, File.WriteAllText with no Encoding argument) writes UTF-8 with
        // no BOM, so a mismatched declaration would ship a file whose XML declaration lies about its own encoding
        // (pwsh's XML parser refuses it); Utf8StringWriter below is the standard fix (override .Encoding, the only
        // member XDocument.Save actually reads it from).
        var document = new XDocument(
            new XDeclaration("1.0", "utf-8", null),
            new XComment(" Generated by Zabbix.PowerShell.csproj's ZabbixGenerateTypesPs1Xml target from Zabbix.Generator's ZabbixTypesEmitter. Do not edit. "),
            types);
        using var writer = new Utf8StringWriter();
        document.Save(writer);
        return writer.ToString().Replace("\r\n", "\n") + "\n";
    }

    /// <summary>
    /// Generates the text of <c>Community.Zabbix.format.ps1xml</c> (loaded by the manifest's <c>FormatsToProcess</c>): a table, a
    /// list and a wide view per read record, derived from the description, so <c>Get-ZbxHost</c> prints a table of the
    /// columns a reader scans (Learn, "Strongly Encouraged Development Guidelines", SC01 "Update Display Information"),
    /// never the long property dump PowerShell falls back to for a record with more than four properties. The columns are a
    /// rule over the model, not a list per entity: the entity's own id and name (<see cref="ZabbixCmdletEmitter.EntityIdField"/>,
    /// <see cref="ZabbixCmdletEmitter.EntityNameField"/>, the same fields the cmdlets select and resolve by), then the
    /// record's scalar fields whose wire name is in <see cref="SummaryWires"/>, in that order, at most
    /// <see cref="MaxColumns"/> in all. The list view is the table's columns followed by every other modelled field, in
    /// the record's order (so <c>Format-List</c> still shows everything the record carries, <c>-Select*</c> collections
    /// included, but not the <c>AdditionalFields</c> bag, which the adapter already surfaces as properties); the wide view
    /// is the name. A nested read record gets views only when it has more than four fields (PowerShell already tables
    /// four or fewer) and the rule finds at least two columns, or when it carries a clock (then the view PowerShell would
    /// pick, a table of its four or fewer fields or a list, so the clock still shows as a date); a singleton read record
    /// (no id, no name) gets a list view. Every clock, in every view, shows as a local date and time; the property keeps
    /// the <c>DateTimeOffset</c>.
    /// </summary>
    /// <param name="description">The description.</param>
    public static string GenerateFormat(ApiDescription description)
    {
        if (description is null) throw new ArgumentNullException(nameof(description));
        Dictionary<string, ServiceDescription> services = description.Services
            .GroupBy(s => s.Object, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.First(), StringComparer.Ordinal);
        var views = new List<XElement>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (TypeDescription type in description.Types.Where(t => t.IsRead).OrderBy(t => t.Name, StringComparer.Ordinal))
        {
            string full = "Community.Zabbix." + (type.Name.StartsWith("Zabbix", StringComparison.Ordinal) ? type.Name : "Zabbix" + type.Name);
            if (!seen.Add(full)) continue;
            IReadOnlyList<FieldDescription> columns = TableColumns(type, services, type.Role == "read" ? description.CmdletShape.Objects.FirstOrDefault(o => o.Object == type.Object)?.View : null);
            string shortName = full["Community.Zabbix.".Length..];
            if (type.Role == "nested-read" && (type.Fields.Length <= 4 || columns.Count < 2))
            {
                // PowerShell's own view of a small record would print a clock as its clock.ns text: one with a clock
                // gets the view PowerShell would pick (a table of four or fewer fields, else a list), its clocks as dates.
                if (type.Fields.Any(IsTime)) views.Add(type.Fields.Length <= 4 ? TableView(shortName, full, type.Fields) : ListView(shortName, full, type.Fields));
                continue;
            }
            if (columns.Count == 0)
            {
                // A singleton (authentication, housekeeping, settings: one document, no id) is read as a list: every
                // modelled field, without the AdditionalFields bag.
                if (type.Role == "read")
                {
                    views.Add(new XElement("View",
                        new XElement("Name", shortName + ".List"),
                        new XElement("ViewSelectedBy", new XElement("TypeName", full)),
                        new XElement("ListControl", new XElement("ListEntries", new XElement("ListEntry", new XElement("ListItems",
                            type.Fields.Select(f => new XElement("ListItem", IsTime(f) ? new XElement("Label", f.Name) : null, Value(f)))))))));
                }
                continue;
            }
            views.Add(new XElement("View",
                new XElement("Name", shortName + ".Table"),
                new XElement("ViewSelectedBy", new XElement("TypeName", full)),
                new XElement("TableControl",
                    new XElement("TableHeaders", columns.Select(c => new XElement("TableColumnHeader", IsTime(c) ? new XElement("Label", c.Name) : null))),
                    new XElement("TableRowEntries", new XElement("TableRowEntry", new XElement("TableColumnItems",
                        columns.Select(c => new XElement("TableColumnItem", Value(c)))))))));
            views.Add(new XElement("View",
                new XElement("Name", shortName + ".List"),
                new XElement("ViewSelectedBy", new XElement("TypeName", full)),
                new XElement("ListControl", new XElement("ListEntries", new XElement("ListEntry", new XElement("ListItems",
                    columns.Concat(type.Fields.Where(f => !columns.Contains(f)))
                        .Select(f => new XElement("ListItem", IsTime(f) ? new XElement("Label", f.Name) : null, Value(f)))))))));
            views.Add(new XElement("View",
                new XElement("Name", shortName + ".Wide"),
                new XElement("ViewSelectedBy", new XElement("TypeName", full)),
                new XElement("WideControl", new XElement("WideEntries", new XElement("WideEntry",
                    new XElement("WideItem", Value(columns.Count > 1 ? columns[1] : columns[0])))))));
        }
        var document = new XDocument(
            new XDeclaration("1.0", "utf-8", null),
            new XComment(" Generated by Zabbix.PowerShell.csproj's ZabbixGenerateTypesPs1Xml target from Zabbix.Generator's ZabbixTypesEmitter.GenerateFormat. Do not edit. "),
            new XElement("Configuration", new XElement("ViewDefinitions", views)));
        using var writer = new Utf8StringWriter();
        document.Save(writer);
        return writer.ToString().Replace("\r\n", "\n") + "\n";
    }

    private static XElement TableView(string shortName, string full, IReadOnlyList<FieldDescription> columns)
        => new("View",
            new XElement("Name", shortName + ".Table"),
            new XElement("ViewSelectedBy", new XElement("TypeName", full)),
            new XElement("TableControl",
                new XElement("TableHeaders", columns.Select(c => new XElement("TableColumnHeader", IsTime(c) ? new XElement("Label", c.Name) : null))),
                new XElement("TableRowEntries", new XElement("TableRowEntry", new XElement("TableColumnItems",
                    columns.Select(c => new XElement("TableColumnItem", Value(c))))))));

    private static XElement ListView(string shortName, string full, IReadOnlyList<FieldDescription> fields)
        => new("View",
            new XElement("Name", shortName + ".List"),
            new XElement("ViewSelectedBy", new XElement("TypeName", full)),
            new XElement("ListControl", new XElement("ListEntries", new XElement("ListEntry", new XElement("ListItems",
                fields.Select(f => new XElement("ListItem", IsTime(f) ? new XElement("Label", f.Name) : null, Value(f))))))));

    // A clock shows as local time; the property itself keeps the instant, so Where-Object/Sort-Object and a script see
    // what the API sent. Zabbix's 0 (never) shows as nothing.
    private static bool IsTime(FieldDescription field) => field.Kind == "clock";

    private static XElement Value(FieldDescription field) => IsTime(field)
        ? new XElement("ScriptBlock", "if ($_." + field.Name + " -and $_." + field.Name + ".ToUnixTimeSeconds() -gt 0) { $_." + field.Name + ".LocalDateTime }")
        : new XElement("PropertyName", field.Name);

    /// <summary>At most this many table columns: what fits a 120-column console with the names Zabbix objects carry.</summary>
    public const int MaxColumns = 6;

    /// <summary>
    /// The wire names that make a table column after the id and the name, in column order: a second name (a host's or a
    /// template's visible <c>name</c> beside its technical <c>host</c>), the identifying key of an item or a macro, the host
    /// it belongs to (items of several hosts are told apart), then what a reader scans a list of monitoring objects for
    /// (the last value, state, kind, severity, when, the value). A field the description marks as one kind's only is left
    /// out. One vocabulary
    /// over every record, so a new record gets a table from its own fields with no line here.
    /// </summary>
    public static IReadOnlyList<string> SummaryWires { get; } =
    [
        "name", "key_", "macro", "hostid", "status", "lastvalue", "lastclock", "state", "type", "value_type", "priority",
        "operating_mode", "available", "eventsource", "clock", "value", "severity", "acknowledged", "value_min",
        "value_avg", "value_max", "source",
    ];

    // A field the description says applies to one kind of record only ("(LOG history only)") is empty on the others,
    // so it makes no column.
    private static bool OneKindOnly(FieldDescription field)
        => field.Summary is { } summary && System.Text.RegularExpressions.Regex.IsMatch(summary, @"\([A-Za-z ]+ only\)");

    /// <summary>The table columns <see cref="GenerateFormat"/> gives <paramref name="type"/>.</summary>
    /// <param name="type">A read or nested read record.</param>
    /// <param name="services">The API objects by name.</param>
    /// <param name="view">The object's reviewed columns (<c>cmdlets.objects.&lt;object&gt;.view</c>, wire names in order),
    /// which win over the rule; <see langword="null"/> or empty when the rule picks them.</param>
    public static IReadOnlyList<FieldDescription> TableColumns(TypeDescription type, IReadOnlyDictionary<string, ServiceDescription> services, IReadOnlyList<string>? view = null)
    {
        if (type is null) throw new ArgumentNullException(nameof(type));
        if (services is null) throw new ArgumentNullException(nameof(services));
        if (view is { Count: > 0 })
            return [.. view.Select(wire => type.Fields.FirstOrDefault(f => f.Wire == wire)).Where(f => f is not null).Select(f => f!)];
        static bool Scalar(FieldDescription f) => !f.Kind.StartsWith("list:", StringComparison.Ordinal)
            && !f.Kind.StartsWith("object:", StringComparison.Ordinal) && !f.Kind.StartsWith(ZabbixTypedFields.Output, StringComparison.Ordinal) && f.Kind != "json";
        FieldDescription? id = type.Role == "read" && type.Object is { } apiObject && services.TryGetValue(apiObject, out ServiceDescription? service)
            ? ZabbixCmdletEmitter.EntityIdField(service, type)
            : type.Fields.FirstOrDefault(f => f.Kind == "id");
        FieldDescription? name = ZabbixCmdletEmitter.EntityNameField(type.Role == "read" ? type.Object ?? string.Empty : string.Empty, type);
        var columns = new List<FieldDescription>(MaxColumns);
        if (id is not null) columns.Add(id);
        if (name is not null && Scalar(name) && !columns.Contains(name)) columns.Add(name);
        foreach (string wire in SummaryWires)
        {
            if (columns.Count == MaxColumns) break;
            if (type.Fields.FirstOrDefault(f => f.Wire == wire) is { } field && Scalar(field) && !OneKindOnly(field) && !columns.Contains(field)) columns.Add(field);
        }
        return columns;
    }

    // The member names the shell expects on these objects, as ETS members on the read
    // records rather than second model properties — a tag's Name (the records say Tag), a host's or template's
    // DisplayName (VisibleName), a user macro's Name (its bare name: {$NAME} -> NAME). Only where the record has no
    // member of that name already.
    private static List<XElement> ShellMembers(TypeDescription type)
    {
        HashSet<string> names = [.. type.Fields.Select(f => f.Name)];
        string? WireMember(string wire) => type.Fields.FirstOrDefault(f => f.Wire == wire)?.Name;
        var extra = new List<XElement>();
        if (WireMember("tag") is { } tag && WireMember("value") is not null && !names.Contains("Name"))
            extra.Add(Alias("Name", tag));
        if (type.Role == "read" && names.Contains("VisibleName") && !names.Contains("DisplayName"))
            extra.Add(Alias("DisplayName", "VisibleName"));
        if (type.Role == "read" && type.Object == "usermacro" && WireMember("macro") is { } macro && !names.Contains("Name"))
            extra.Add(new XElement("ScriptProperty",
                new XElement("Name", "Name"),
                new XElement("GetScriptBlock", "$this." + macro + " -replace '^\\{\\$(.*)\\}$', '$1'")));
        if (Shown(type) is { } shown)
            extra.Add(new XElement("ScriptMethod", new XElement("Name", "ToString"), new XElement("Script", shown)));
        // A clock as a local date beside the instant (Zabbix.PowerShell.ZabbixTimeMembers): a code property, which
        // runs no script, so it works in a constrained language session.
        foreach ((string member, string clock) in new[] { ("Time", "clock"), ("LastTime", "lastclock") })
        {
            if (names.Contains(member) || type.Fields.FirstOrDefault(f => f.Wire == clock) is not { Kind: "clock" } field) continue;
            if (field.Name != (clock == "clock" ? "Clock" : "LastClock")) continue;
            extra.Add(new XElement("CodeProperty",
                new XElement("Name", member),
                new XElement("GetCodeReference",
                    new XElement("TypeName", "Community.Zabbix.PowerShell.ZabbixTimeMembers"),
                    new XElement("MethodName", member))));
        }
        return extra;
    }

    // A record's text where the shell shows it as a value — an item of a host's Groups or Tags in Format-List/-Table,
    // "{Linux servers, Databases}" — rather than the C# record's compiler ToString, which prints every member,
    // AdditionalFields included: a tag as "tag: value", otherwise the name, else the id.
    private static string? Shown(TypeDescription type)
    {
        string? WireMember(string wire) => type.Fields.FirstOrDefault(f => f.Wire == wire)?.Name;
        if (WireMember("tag") is { } tag && WireMember("value") is { } value)
            return "if ($this." + value + ") { '{0}: {1}' -f $this." + tag + ", $this." + value + " } else { [string]$this." + tag + " }";
        FieldDescription? name = ZabbixCmdletEmitter.EntityNameField(type.Role == "read" ? type.Object ?? string.Empty : string.Empty, type);
        FieldDescription? id = type.Fields.FirstOrDefault(f => f.Kind == "id");
        if (name is not null && id is not null && name.Name != id.Name)
            return "if ($null -ne $this." + name.Name + ") { [string]$this." + name.Name + " } else { [string]$this." + id.Name + " }";
        if ((name ?? id) is { } only) return "[string]$this." + only.Name;
        return null;
    }

    private static XElement Alias(string name, string referenced)
        => new("AliasProperty", new XElement("Name", name), new XElement("ReferencedMemberName", referenced));

    private sealed class Utf8StringWriter : StringWriter
    {
        public override Encoding Encoding => Encoding.UTF8;
    }
}
