using System.Text.Json;

namespace Community.Zabbix.Generator;

/// <summary>
/// The PowerShell module's reviewed shape where no rule over the model decides it (<c>cmdlets</c> in
/// <c>schema/zabbix-api.json</c>, carried from <c>schema/overlay.json</c>): what each API object's cmdlets do
/// differently, the nested-record builders, and the get options every <c>Get-</c> takes as a switch or as an enum
/// array. <see cref="ZabbixCmdletEmitter"/> reads it; the records and clients do not.
/// </summary>
/// <param name="Objects">Per API object.</param>
/// <param name="Builders">The <c>New-Zbx&lt;Concept&gt;</c> builders, in the order they are emitted.</param>
/// <param name="GetSwitches">The get options taken as switches, in the order they are declared.</param>
/// <param name="GetLists">The get options taken as enum arrays, in the order they are declared.</param>
internal sealed record CmdletDescription(EquatableArray<CmdletObject> Objects, EquatableArray<BuilderDescription> Builders, EquatableArray<GetSwitch> GetSwitches, EquatableArray<GetList> GetLists)
{
    /// <summary>No reviewed shape: every object generated by the rules alone, no builder, no switch, no list.</summary>
    public static CmdletDescription Empty { get; } = new([], [], [], []);

    /// <summary>
    /// The description's <c>cmdlets</c> section; <see cref="Empty"/> when it has none. An entry that cannot be read is a
    /// <see cref="ZabbixDiagnostics.Malformed"/> problem at its name, and left out.
    /// </summary>
    /// <param name="root">The description.</param>
    /// <param name="problems">Receives what was left out.</param>
    public static CmdletDescription Read(JsonElement root, List<EmitProblem> problems)
    {
        if (!root.TryGetProperty("cmdlets", out JsonElement section)) return Empty;
        if (section.ValueKind != JsonValueKind.Object)
        {
            problems.Add(new(ZabbixDiagnostics.Malformed, "the cmdlets section is not an object and is left out", "cmdlets", null));
            return Empty;
        }
        return new(
            Entries(section, "objects", problems, ReadObject),
            Items(section, "builders", problems, ReadBuilder),
            Entries(section, "getSwitches", problems, static (wire, entry) => new GetSwitch(wire, Required(entry, "parameter"), Required(entry, "summary"))),
            Entries(section, "getLists", problems, static (wire, entry) => new GetList(wire, Required(entry, "parameter"), Required(entry, "summary"))));
    }

    /// <summary>The section with every builder's record named as <paramref name="name"/> names records.</summary>
    /// <param name="name">The record's new name for its old one.</param>
    public CmdletDescription Renamed(Func<string, string> name)
        => this with { Builders = [.. Builders.Select(b => b with { Record = name(b.Record) })] };

    private static CmdletObject ReadObject(string apiObject, JsonElement entry) => new(
        apiObject,
        ApiDescription.Text(entry, "skip"),
        ApiDescription.Text(entry, "handWrittenGet"),
        ApiDescription.Text(entry, "interfaceShorthand"),
        ApiDescription.Text(entry, "manyPerId"),
        [.. Pairs(entry, "switches").Select(p => Members(p.Wire, p.Value))],
        ValueForms(entry),
        entry.TryGetProperty("names", out JsonElement names) ? new NameFields(Required(names, "display"), Required(names, "technical")) : null,
        [.. Pairs(entry, "unhide").Select(p => new UnhiddenField(p.Wire, p.Value.GetString() ?? throw new InvalidOperationException("an unhidden property name is not a string")))],
        ApiDescription.Strings(entry, "view"));

    private static BuilderDescription ReadBuilder(JsonElement entry) => new(
        Required(entry, "concept"),
        Required(entry, "record"),
        ApiDescription.Strings(entry, "positional"),
        Required(entry, "noun"),
        Required(entry, "use"),
        Required(entry, "what"),
        ValueForms(entry),
        [.. Pairs(entry, "ownerSupplied").Select(p => new WireNote(p.Wire, p.Value.GetString() ?? throw new InvalidOperationException("an ownerSupplied sentence is not a string")))]);

    private static SwitchField Members(string wire, JsonElement members)
        => members.ValueKind == JsonValueKind.Array && members.GetArrayLength() == 2
            ? new(wire, members[0].GetString()!, members[1].GetString()!)
            : throw new InvalidOperationException("the switch " + wire + " does not name its two members");

    private static EquatableArray<ValueForm> ValueForms(JsonElement entry)
        => [.. Pairs(entry, "valueForms").Select(p => new ValueForm(p.Wire, [.. p.Value.EnumerateArray().Select(a => a.GetString() ?? throw new InvalidOperationException("an attribute name is not a string"))]))];

    private static IEnumerable<(string Wire, JsonElement Value)> Pairs(JsonElement entry, string name)
        => entry.TryGetProperty(name, out JsonElement map) && map.ValueKind == JsonValueKind.Object
            ? map.EnumerateObject().Select(p => (p.Name, p.Value))
            : [];

    private static string Required(JsonElement entry, string name)
        => ApiDescription.Text(entry, name) ?? throw new InvalidOperationException("it has no " + name);

    // A map's entries (keyed by name), each read on its own: one that cannot be read is left out and reported.
    private static EquatableArray<T> Entries<T>(JsonElement section, string name, List<EmitProblem> problems, Func<string, JsonElement, T> read)
        where T : IEquatable<T>
    {
        var list = new List<T>();
        foreach ((string key, JsonElement entry) in Pairs(section, name))
        {
            try
            {
                list.Add(read(key, entry));
            }
            catch (Exception exception) when (exception is KeyNotFoundException or InvalidOperationException or IndexOutOfRangeException)
            {
                problems.Add(new(ZabbixDiagnostics.Malformed, "the cmdlets entry cannot be read and is left out: " + exception.Message, key, null));
            }
        }
        return [.. list];
    }

    // A list's entries, each read on its own: one that cannot be read is left out and reported at its concept.
    private static EquatableArray<T> Items<T>(JsonElement section, string name, List<EmitProblem> problems, Func<JsonElement, T> read)
        where T : IEquatable<T>
    {
        var list = new List<T>();
        if (!section.TryGetProperty(name, out JsonElement items) || items.ValueKind != JsonValueKind.Array) return [];
        int index = 0;
        foreach (JsonElement entry in items.EnumerateArray())
        {
            try
            {
                list.Add(read(entry));
            }
            catch (Exception exception) when (exception is KeyNotFoundException or InvalidOperationException)
            {
                string subject = entry.ValueKind == JsonValueKind.Object ? ApiDescription.Text(entry, "concept") ?? "cmdlets." + name + "[" + index + "]" : "cmdlets." + name + "[" + index + "]";
                problems.Add(new(ZabbixDiagnostics.Malformed, "the builder cannot be read and is left out: " + exception.Message, subject, null));
            }
            index++;
        }
        return [.. list];
    }
}
