using System.Globalization;
using System.Text;

namespace Community.Zabbix.PowerShell.HelpGen;

/// <summary>
/// The per-command reference pages <c>Get-Help -Online</c> opens: one Markdown page per
/// command in PlatyPS's section order (SYNOPSIS, SYNTAX, DESCRIPTION, EXAMPLES, PARAMETERS, INPUTS, OUTPUTS, RELATED
/// LINKS), built from the same <see cref="CmdletDoc"/> the MAML is, so the page and <c>Get-Help</c> cannot disagree, and
/// an index page. Written by <see cref="ZabbixBuildHelpTask"/> into the build's <c>reference/</c> folder under the intermediate output, never the source tree.
/// </summary>
internal static class MarkdownWriter
{
    private const string Marker = "<!-- GENERATED by Zabbix.PowerShell.HelpGen (ZabbixBuildHelp target) from the cmdlets' doc comments. DO NOT EDIT. -->";

    /// <summary>Every page: <c>(file name, text)</c>, the index (<c>README.md</c>) first.</summary>
    /// <param name="cmdlets">The commands.</param>
    /// <param name="onlineBase">Where the pages are read online.</param>
    /// <param name="moduleName">The module the commands are in (Community.Zabbix, Community.Zabbix.Agent, Community.Zabbix.Proxy), the index's title.</param>
    /// <param name="types">What each type a command takes or writes is (<see cref="TypeSummaries"/>).</param>
    /// <param name="conceptTopic">The module's concept topic, which the index and each page's related links name.</param>
    public static IEnumerable<(string Name, string Text)> Build(IReadOnlyList<CmdletDoc> cmdlets, string onlineBase, string moduleName, IReadOnlyDictionary<string, string> types, string conceptTopic = "about_Community.Zabbix")
    {
        CmdletDoc[] ordered = [.. cmdlets.OrderBy(c => c.Noun, StringComparer.Ordinal).ThenBy(c => c.Verb, StringComparer.Ordinal)];
        var index = new StringBuilder();
        index.Append(Marker).Append("\n# PowerShell module ").Append(moduleName).Append(": command reference\n\n");
        index.Append("One page per command, the same text `Get-Help <command> -Full` shows; `Get-Help <command> -Online` opens the page. ");
        index.Append("Concepts are in `Get-Help ").Append(conceptTopic).Append("`.\n\n| Command | Synopsis |\n| --- | --- |\n");
        foreach (CmdletDoc cmdlet in ordered)
            index.Append("| [").Append(cmdlet.Name).Append("](").Append(cmdlet.Name).Append(".md) | ").Append(Cell(cmdlet.Synopsis)).Append(" |\n");
        yield return ("README.md", index.ToString());

        foreach (CmdletDoc cmdlet in ordered)
            yield return (cmdlet.Name + ".md", Page(cmdlet, onlineBase, types, conceptTopic));
    }

    private static string Page(CmdletDoc cmdlet, string onlineBase, IReadOnlyDictionary<string, string> types, string conceptTopic)
    {
        IReadOnlyList<ParameterDoc> documented = [.. cmdlet.Parameters];
        var page = new StringBuilder();
        page.Append(Marker).Append("\n# ").Append(cmdlet.Name).Append("\n\n## SYNOPSIS\n\n").Append(cmdlet.Synopsis).Append("\n\n## SYNTAX\n");
        IReadOnlyList<string> sets = cmdlet.ParameterSets();
        foreach (string set in sets)
        {
            if (set.Length > 0)
                page.Append("\n### ").Append(set).Append(string.Equals(set, cmdlet.DefaultParameterSet, StringComparison.Ordinal) || sets.Count == 1 ? " (Default)" : string.Empty).Append('\n');
            page.Append("\n```\n").Append(cmdlet.Name);
            foreach ((ParameterDoc parameter, ParameterUse use) in cmdlet.In(set).OrderBy(p => p.Use.Position ?? int.MaxValue))
                page.Append(' ').Append(Syntax(parameter, use));
            foreach (ParameterDoc engine in MamlWriter.EngineParameters(cmdlet))
                page.Append(" [-").Append(engine.Name).Append(engine.TypeText == "SwitchParameter" ? string.Empty : " <" + engine.TypeText + ">").Append(']');
            page.Append(" [<CommonParameters>]\n```\n");
        }
        page.Append("\n## DESCRIPTION\n\n").Append(cmdlet.Description).Append("\n\n## EXAMPLES\n");
        int number = 0;
        foreach ((string title, string code, string remarks) in cmdlet.Examples)
        {
            number++;
            page.Append("\n### Example ").Append(number.ToString(CultureInfo.InvariantCulture)).Append(": ").Append(title).Append("\n\n```powershell\n")
                .Append(code).Append("\n```\n\n").Append(remarks.Replace("\n", "\n\n", StringComparison.Ordinal)).Append('\n');
        }
        page.Append("\n## PARAMETERS\n");
        foreach (ParameterDoc parameter in documented)
        {
            IEnumerable<string> inSets = parameter.Uses.Select(u => u.Set.Length == 0 ? "(All)" : u.Set).Distinct(StringComparer.Ordinal);
            page.Append("\n### -").Append(parameter.Name).Append("\n\n").Append(parameter.Description).Append("\n\n| | |\n| --- | --- |\n")
                .Append("| Type | `").Append(parameter.DisplayType).Append("` |\n")
                .Append("| Parameter sets | ").Append(string.Join(", ", inSets)).Append(" |\n")
                .Append("| Aliases | ").Append(parameter.Aliases.Count == 0 ? "none" : string.Join(", ", parameter.Aliases)).Append(" |\n")
                .Append("| Required | ").Append(string.Join(", ", parameter.Uses.Select(u => u.Mandatory ? "True" : "False").Distinct(StringComparer.Ordinal))).Append(" |\n")
                .Append("| Position | ").Append(string.Join(", ", parameter.Uses.Select(u => u.Position?.ToString(CultureInfo.InvariantCulture) ?? "Named").Distinct(StringComparer.Ordinal))).Append(" |\n")
                .Append("| Default value | ").Append(parameter.DefaultValue ?? "None").Append(" |\n")
                .Append("| Pipeline input | ").Append(PipelineInput(parameter)).Append(" |\n")
                .Append("| Wildcards | ").Append(parameter.Wildcards ? "True" : "False").Append(" |\n");
        }
        foreach (ParameterDoc engine in MamlWriter.EngineParameters(cmdlet))
            page.Append("\n### -").Append(engine.Name).Append("\n\n").Append(engine.Description).Append('\n');
        page.Append("\n### CommonParameters\n\nThis command supports the common parameters: `-Debug`, `-ErrorAction`, `-ErrorVariable`, `-InformationAction`, ")
            .Append("`-InformationVariable`, `-OutBuffer`, `-OutVariable`, `-PipelineVariable`, `-ProgressAction`, `-Verbose`, `-WarningAction`, `-WarningVariable` ")
            .Append("(about_CommonParameters).\n\n## INPUTS\n\n");
        (string Type, string Description)[] inputs = [.. MamlWriter.Inputs(documented, types)];
        page.Append(inputs.Length == 0 ? "None.\n" : string.Concat(inputs.Select(i => "- `" + i.Type + "`: " + i.Description + "\n")));
        page.Append("\n## OUTPUTS\n\n");
        page.Append(cmdlet.OutputTypes.Count == 0 ? "None.\n" : string.Concat(cmdlet.OutputTypes.Select(o => "- `" + o + "`: " + MamlWriter.Output(o, types) + "\n")));
        page.Append("\n## RELATED LINKS\n\n- [Online version](").Append(onlineBase).Append(cmdlet.Name).Append(".html)\n- `Get-Help ").Append(conceptTopic).Append("`\n- [Command index](README.md)\n");
        return page.ToString();
    }

    private static string Syntax(ParameterDoc parameter, ParameterUse use)
    {
        string name = use.Position is null ? "-" + parameter.Name : "[-" + parameter.Name + "]";
        string text = parameter.IsSwitch ? name : name + " <" + parameter.DisplayType + ">";
        return use.Mandatory ? text : "[" + text + "]";
    }

    private static string PipelineInput(ParameterDoc parameter)
    {
        bool byValue = parameter.Uses.Any(u => u.ValueFromPipeline);
        bool byName = parameter.Uses.Any(u => u.ValueFromPipelineByPropertyName);
        return (byValue, byName) switch
        {
            (true, true) => "True (ByValue, ByPropertyName)",
            (true, false) => "True (ByValue)",
            (false, true) => "True (ByPropertyName)",
            _ => "False",
        };
    }

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
}
