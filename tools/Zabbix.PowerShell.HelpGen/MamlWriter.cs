using System.Xml.Linq;

namespace Community.Zabbix.PowerShell.HelpGen;

/// <summary>
/// Builds the module's MAML help XML directly from <see cref="CmdletDoc"/> records — no PlatyPS, no Markdown
/// round-trip. A cmdlet's examples are its
/// <see cref="CmdletDoc.Examples"/>: its help script's (<c>Examples/&lt;Verb-Noun&gt;.ps1</c>), or the generator's. The
/// syntax block carries one entry per parameter set, with each parameter's type, position and required-ness in that
/// set — what PowerShell's own help shows for a script cmdlet.
/// </summary>
internal static class MamlWriter
{
    private static readonly XNamespace s_maml = "http://schemas.microsoft.com/maml/2004/10";
    private static readonly XNamespace s_command = "http://schemas.microsoft.com/maml/dev/command/2004/10";
    private static readonly XNamespace s_dev = "http://schemas.microsoft.com/maml/dev/2004/10";

    private static readonly string[] s_commonParameters =
    [
        "Verbose", "Debug", "ErrorAction", "WarningAction", "InformationAction", "ErrorVariable",
        "WarningVariable", "InformationVariable", "OutVariable", "OutBuffer", "PipelineVariable", "ProgressAction",
        "WhatIf", "Confirm",
    ];

    /// <summary>Builds the full <c>helpItems</c> document for every cmdlet in <paramref name="cmdlets"/>.</summary>
    /// <param name="cmdlets">The commands.</param>
    /// <param name="onlineBase">Where the reference pages are read online (ends in <c>/</c>).</param>
    /// <param name="types">What each type a command takes or writes is (<see cref="TypeSummaries"/>).</param>
    /// <param name="conceptTopic">The module's concept topic, each command's last related link.</param>
    public static XDocument Build(IReadOnlyList<CmdletDoc> cmdlets, string onlineBase, IReadOnlyDictionary<string, string> types, string conceptTopic = "about_Community.Zabbix")
    {
        var helpItems = new XElement(
            "helpItems",
            new XAttribute(XNamespace.Xmlns + "maml", s_maml),
            new XAttribute(XNamespace.Xmlns + "command", s_command),
            new XAttribute(XNamespace.Xmlns + "dev", s_dev),
            new XAttribute("schema", "maml"));

        foreach (CmdletDoc cmdlet in cmdlets.OrderBy(c => c.Name, StringComparer.Ordinal))
            helpItems.Add(BuildCommand(cmdlet, onlineBase, types, conceptTopic));

        return new XDocument(
            new XComment(
                " GENERATED by Zabbix.PowerShell.HelpGen (ZabbixBuildHelp target) from Commands/*.cs and the "
                + "generator's cmdlets. DO NOT EDIT: hand edits are lost on the next build. "),
            helpItems);
    }

    private static XElement BuildCommand(CmdletDoc cmdlet, string onlineBase, IReadOnlyDictionary<string, string> types, string conceptTopic)
    {
        IReadOnlyList<ParameterDoc> documented = [.. cmdlet.Parameters.Where(p => !s_commonParameters.Contains(p.Name, StringComparer.Ordinal))];
        IReadOnlyList<ParameterDoc> risk = [.. EngineParameters(cmdlet)];

        return new XElement(
            s_command + "command",
            new XElement(
                s_command + "details",
                new XElement(s_command + "name", cmdlet.Name),
                new XElement(s_maml + "description", new XElement(s_maml + "para", cmdlet.Synopsis)),
                new XElement(s_command + "verb", cmdlet.Verb),
                new XElement(s_command + "noun", cmdlet.Noun)),
            new XElement(s_maml + "description", new XElement(s_maml + "para", cmdlet.Description)),
            // One syntax line per parameter set, the default set first (Learn, "How to add syntax to a cmdlet help topic").
            new XElement(
                s_command + "syntax",
                cmdlet.ParameterSets().Select(set => new XElement(
                    s_command + "syntaxItem",
                    new XElement(s_maml + "name", cmdlet.Name),
                    cmdlet.In(set)
                        .Where(p => !s_commonParameters.Contains(p.Parameter.Name, StringComparer.Ordinal))
                        .OrderBy(p => p.Use.Position ?? int.MaxValue)
                        .Select(p => BuildParameter(p.Parameter, p.Use, full: false)),
                    risk.Select(p => BuildParameter(p, p.Uses[0], full: false))))),
            new XElement(s_command + "parameters", documented.Concat(risk).Select(p => BuildParameter(p, Summary(p), full: true))),
            new XElement(s_command + "inputTypes", InputTypes(documented, types)),
            new XElement(s_command + "returnValues", ReturnValues(cmdlet, types)),
            new XElement(s_command + "examples", BuildExamples(cmdlet)),
            new XElement(
                s_maml + "relatedLinks",
                // The first link is what Get-Help -Online opens when the command sets no HelpUri.
                Link("Online Version:", onlineBase + cmdlet.Name + ".html"),
                Link(conceptTopic, string.Empty)));
    }

    /// <summary>The parameters the engine adds to <paramref name="cmdlet"/> from its <c>[Cmdlet]</c> attribute, which its help lists.</summary>
    /// <param name="cmdlet">The command.</param>
    internal static IEnumerable<ParameterDoc> EngineParameters(CmdletDoc cmdlet)
        => (cmdlet.SupportsPaging ? s_pagingParameters : []).Concat(cmdlet.SupportsShouldProcess ? s_riskParameters : []);

    // -First/-Skip/-IncludeTotalCount are the engine's paging parameters, added to a SupportsPaging command.
    private static readonly IReadOnlyList<ParameterDoc> s_pagingParameters =
    [
        new() { Name = "First", TypeText = "UInt64", Description = "Gets only the first this many objects: the server returns no more.", Aliases = [], Uses = [new(string.Empty, false, null, false, false)] },
        new() { Name = "Skip", TypeText = "UInt64", Description = "Passes over this many objects before it writes the rest.", Aliases = [], Uses = [new(string.Empty, false, null, false, false)] },
        new() { Name = "IncludeTotalCount", TypeText = "SwitchParameter", Description = "Writes, after the objects, how many objects the selection finds before -First and -Skip.", Aliases = [], Uses = [new(string.Empty, false, null, false, false)] },
    ];

    // -WhatIf/-Confirm are common parameters PowerShell adds to a SupportsShouldProcess command; its help lists them.
    private static readonly IReadOnlyList<ParameterDoc> s_riskParameters =
    [
        new() { Name = "WhatIf", TypeText = "SwitchParameter", Description = "Shows what would happen if the command ran. The command does not run.", Aliases = ["wi"], Uses = [new(string.Empty, false, null, false, false)] },
        new() { Name = "Confirm", TypeText = "SwitchParameter", Description = "Prompts for confirmation before the command changes anything.", Aliases = ["cf"], Uses = [new(string.Empty, false, null, false, false)] },
    ];

    // A parameter's one entry in the PARAMETERS section summarizes its uses: required when it is mandatory in every
    // set it is in, the position it has (named when the sets disagree or it has none), and every way it binds from
    // the pipeline.
    private static ParameterUse Summary(ParameterDoc parameter)
    {
        IReadOnlyList<ParameterUse> uses = parameter.Uses.Count == 0 ? [new(string.Empty, parameter.Mandatory, null, false, false)] : parameter.Uses;
        int?[] positions = [.. uses.Select(u => u.Position).Distinct()];
        return new ParameterUse(
            string.Empty,
            uses.All(u => u.Mandatory),
            positions.Length == 1 ? positions[0] : null,
            uses.Any(u => u.ValueFromPipeline),
            uses.Any(u => u.ValueFromPipelineByPropertyName));
    }

    private static XElement BuildParameter(ParameterDoc parameter, ParameterUse use, bool full) => new(
        s_command + "parameter",
        new XAttribute("required", use.Mandatory ? "true" : "false"),
        new XAttribute("variableLength", parameter.TypeText.Contains("[]", StringComparison.Ordinal) ? "true" : "false"),
        new XAttribute("globbing", parameter.Wildcards ? "true" : "false"),
        new XAttribute("pipelineInput", PipelineInput(use)),
        new XAttribute("position", use.Position is int at ? at.ToString(System.Globalization.CultureInfo.InvariantCulture) : "named"),
        new XAttribute("aliases", parameter.Aliases.Count == 0 ? "none" : string.Join(", ", parameter.Aliases)),
        new XElement(s_maml + "name", parameter.Name),
        full ? new XElement(s_maml + "description", new XElement(s_maml + "para", parameter.Description)) : null,
        parameter.IsSwitch ? null : new XElement(s_command + "parameterValue", new XAttribute("required", "true"), new XAttribute("variableLength", "false"), parameter.DisplayType),
        full ? new XElement(s_dev + "type", new XElement(s_maml + "name", parameter.DisplayType)) : null,
        full && parameter.DefaultValue is { } defaultValue ? new XElement(s_dev + "defaultValue", defaultValue) : null);

    private static string PipelineInput(ParameterUse use) => (use.ValueFromPipeline, use.ValueFromPipelineByPropertyName) switch
    {
        (true, true) => "True (ByValue, ByPropertyName)",
        (true, false) => "True (ByValue)",
        (false, true) => "True (ByPropertyName)",
        _ => "False",
    };

    private static IEnumerable<XElement> InputTypes(IReadOnlyList<ParameterDoc> documented, IReadOnlyDictionary<string, string> types)
    {
        (string Type, string Description)[] inputs = [.. Inputs(documented, types)];
        return inputs.Length == 0
            ? [TypeEntry("inputType", "None", "This command takes no pipeline input.")]
            : inputs.Select(input => TypeEntry("inputType", input.Type, input.Description));
    }

    /// <summary>
    /// Each type the command takes from the pipeline, described by the parameters that bind it and how, and
    /// by what the type is.
    /// </summary>
    internal static IEnumerable<(string Type, string Description)> Inputs(IReadOnlyList<ParameterDoc> documented, IReadOnlyDictionary<string, string> types)
        => documented.Where(p => p.Uses.Any(u => u.ValueFromPipeline || u.ValueFromPipelineByPropertyName))
            .GroupBy(p => p.DisplayType, StringComparer.Ordinal)
            .Select(group => (group.Key, string.Join(" ", new[]
            {
                "Bound to " + string.Join(", ", group.Select(p => "-" + p.Name + " (" + PipelineInput(p.Uses.First(u => u.ValueFromPipeline || u.ValueFromPipelineByPropertyName))[6..^1] + ")")) + ".",
                TypeSummaries.Of(types, group.Key),
            }.OfType<string>())));

    private static IEnumerable<XElement> ReturnValues(CmdletDoc cmdlet, IReadOnlyDictionary<string, string> types)
        => cmdlet.OutputTypes.Count == 0
            ? [TypeEntry("returnValue", "None", "This command writes nothing to the pipeline.")]
            : cmdlet.OutputTypes.Select(type => TypeEntry("returnValue", type, Output(type, types)));

    /// <summary>What the type a command writes is, from its documentation summary.</summary>
    internal static string Output(string type, IReadOnlyDictionary<string, string> types)
        => TypeSummaries.Of(types, type) ?? "The objects this command writes.";

    private static XElement TypeEntry(string kind, string type, string description) => new(
        s_command + kind,
        new XElement(s_dev + "type", new XElement(s_maml + "name", type)),
        new XElement(s_maml + "description", description.Length == 0 ? null : new XElement(s_maml + "para", description)));

    private static XElement Link(string text, string uri) => new(
        s_maml + "navigationLink",
        new XElement(s_maml + "linkText", text),
        new XElement(s_maml + "uri", uri));

    private static IEnumerable<XElement> BuildExamples(CmdletDoc cmdlet)
        => cmdlet.Examples.Select((example, index) => new XElement(
            s_command + "example",
            new XElement(s_maml + "title", $"-------------------------- Example {index + 1}: {example.Title} --------------------------"),
            new XElement(s_dev + "code", example.Code),
            new XElement(
                s_dev + "remarks",
                example.Remarks.Split('\n').Select(line => new XElement(s_maml + "para", line)))));
}
