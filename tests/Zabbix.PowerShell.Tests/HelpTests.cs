    [MemberData(nameof(ModuleUnderTest.Names), MemberType = typeof(ModuleUnderTest))]
    public void Every_non_common_parameter_documented_in_the_MAML_file_has_a_description(string module)
    {
        XNamespace command = "http://schemas.microsoft.com/maml/dev/command/2004/10";
        XNamespace maml = "http://schemas.microsoft.com/maml/2004/10";
        XDocument document = XDocument.Load(ModuleUnderTest.Named(module).HelpFile);

        var violations = new List<string>();
        foreach (XElement entry in document.Descendants(command + "command"))
