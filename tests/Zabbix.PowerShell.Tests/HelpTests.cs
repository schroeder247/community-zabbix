        string[] leaks = [.. XDocument.Load(ModuleUnderTest.Named(module).HelpFile).Descendants(maml + "para").Select(p => p.Value).Where(p => note.IsMatch(p)).Distinct()];

        Assert.Empty(leaks);
    }

    private static List<string> StaticBindingProblems(Shell shell, IEnumerable<string> scripts)
    {
        var problems = new List<string>();
        foreach (string script in scripts)
        {
            System.Management.Automation.Language.ScriptBlockAst ast = System.Management.Automation.Language.Parser.ParseInput(script, out _, out System.Management.Automation.Language.ParseError[] errors);
            if (errors.Length > 0)
            {
                problems.Add($"{script}: {errors[0].Message}");
                continue;
            }
            foreach (System.Management.Automation.Language.CommandAst commandAst in ast.FindAll(a => a is System.Management.Automation.Language.CommandAst, true).Cast<System.Management.Automation.Language.CommandAst>())
            {
                string? name = commandAst.GetCommandName();
                if (name is null || !name.Contains("-Zbx", StringComparison.Ordinal)) continue;
                Run found = shell.Invoke($"Get-Command '{name}' -Module Community.Zabbix, Community.Zabbix.Agent, Community.Zabbix.Proxy -ErrorAction SilentlyContinue | ForEach-Object Name");
                if (found.Output.Count == 0)
                {
                    problems.Add($"{script}: no command {name}");
                    continue;
                }
                // The binder resolves the command through the thread's default runspace: this shell's, for the call.
                System.Management.Automation.Runspaces.Runspace? before = System.Management.Automation.Runspaces.Runspace.DefaultRunspace;
                System.Management.Automation.Runspaces.Runspace.DefaultRunspace = shell.Runspace;
                try
                {
                    System.Management.Automation.Language.StaticBindingResult result = System.Management.Automation.Language.StaticParameterBinder.BindCommand(commandAst, resolve: true);
                    foreach ((string parameter, System.Management.Automation.Language.StaticBindingError error) in result.BindingExceptions)
                        problems.Add($"{script}: -{parameter}: {error.BindingException.Message}");
                }
                finally
                {
                    System.Management.Automation.Runspaces.Runspace.DefaultRunspace = before;
                }
            }
        }
        return problems;
    }

    [Theory]
    [MemberData(nameof(ModuleUnderTest.Names), MemberType = typeof(ModuleUnderTest))]
    public void No_help_syntax_names_a_parameter_type_with_a_csharp_modifier(string module)
    {
        // A property declared with a modifier (`public new …`, hiding an inherited member of the same name) must not leak
        // the modifier into the syntax: a source parser that read it as part of the type would show
        // "-Host <new ZabbixReference<…>>".
        string[] offenders = [.. Directory.EnumerateFiles(ModuleUnderTest.Named(module).ReferenceDirectory, "*.md")
            .Where(file => System.Text.RegularExpressions.Regex.IsMatch(File.ReadAllText(file), @"<(new|override|sealed|static) "))
            .Select(Path.GetFileName)!];

        Assert.Empty(offenders);
    }
