    [Theory]
    [MemberData(nameof(ModuleUnderTest.Names), MemberType = typeof(ModuleUnderTest))]
    public void Every_documented_cmdlet_in_the_MAML_file_has_a_synopsis_a_description_and_at_least_one_example(string module)
    {
        XNamespace command = "http://schemas.microsoft.com/maml/dev/command/2004/10";
        XNamespace maml = "http://schemas.microsoft.com/maml/2004/10";
        XDocument document = XDocument.Load(ModuleUnderTest.Named(module).HelpFile);

        var violations = new List<string>();
        foreach (XElement entry in document.Descendants(command + "command"))
        {
            string name = entry.Element(command + "details")!.Element(command + "name")!.Value;
            string synopsis = entry.Element(command + "details")!.Element(maml + "description")!.Element(maml + "para")!.Value.Trim();
            string description = entry.Element(maml + "description")!.Element(maml + "para")!.Value.Trim();
            int examples = entry.Element(command + "examples")?.Elements(command + "example").Count() ?? 0;

            if (synopsis.Length == 0) violations.Add($"{name}: no synopsis");
            if (description.Length == 0) violations.Add($"{name}: no description");
            if (examples == 0) violations.Add($"{name}: no examples");
        }

        Assert.Empty(violations);
    }

    [Theory]
    [MemberData(nameof(ModuleUnderTest.Names), MemberType = typeof(ModuleUnderTest))]
    public void No_description_in_the_MAML_file_is_empty(string module)
    {
        // An OUTPUTS type is documented in the assembly that declares it, not in the cmdlet's source: its description
        // comes from that assembly's XML documentation file, so a parser that read only the cmdlet sources left it empty.
        XNamespace maml = "http://schemas.microsoft.com/maml/2004/10";
        XDocument document = XDocument.Load(ModuleUnderTest.Named(module).HelpFile);

        Assert.Empty(document.Descendants(maml + "description").Where(description => description.Value.Trim().Length == 0)
            .Select(description => description.Parent?.ToString(SaveOptions.DisableFormatting)[..Math.Min(120, description.Parent.ToString().Length)]));
    }

