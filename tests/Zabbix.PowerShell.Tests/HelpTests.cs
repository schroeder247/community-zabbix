    [Theory]
    [MemberData(nameof(ModuleUnderTest.Names), MemberType = typeof(ModuleUnderTest))]
    public void No_help_example_leaves_a_mandatory_parameter_unbound(string module)
    {
        // An example a reader pastes must run, not stop to prompt: every Zabbix command in it binds a parameter set whose
        // mandatory parameters are all given, or come from the pipeline when the command is piped into.
        XNamespace command = "http://schemas.microsoft.com/maml/dev/command/2004/10";
        XNamespace dev = "http://schemas.microsoft.com/maml/dev/2004/10";
        string[] examples = [.. XDocument.Load(ModuleUnderTest.Named(module).HelpFile).Descendants(command + "example").Select(e => e.Element(dev + "code")!.Value)];
        using Shell shell = Shell.Open();

        Assert.Empty(UnboundMandatoryParameters(shell, examples));
    }

    private static List<string> UnboundMandatoryParameters(Shell shell, IEnumerable<string> scripts)
    {
        var problems = new List<string>();
        foreach (string script in scripts)
        {
            System.Management.Automation.Language.ScriptBlockAst ast = System.Management.Automation.Language.Parser.ParseInput(script, out _, out System.Management.Automation.Language.ParseError[] errors);
            if (errors.Length > 0) continue;   // Every_help_example_binds_to_real_commands_and_parameters reports it
            foreach (System.Management.Automation.Language.CommandAst commandAst in ast.FindAll(a => a is System.Management.Automation.Language.CommandAst, true).Cast<System.Management.Automation.Language.CommandAst>())
            {
                string? name = commandAst.GetCommandName();
                if (name is null || !name.Contains("-Zbx", StringComparison.Ordinal)) continue;
                // A splatted hashtable binds what the static binder cannot see.
                if (commandAst.CommandElements.Any(element => element is System.Management.Automation.Language.VariableExpressionAst { Splatted: true })) continue;
                Run found = shell.Invoke($"Get-Command '{name}' -Module Community.Zabbix, Community.Zabbix.Agent, Community.Zabbix.Proxy -ErrorAction SilentlyContinue");
                if (found.Output.Count == 0 || found.Output[0].BaseObject is not CommandInfo info) continue;
                bool piped = commandAst.Parent is System.Management.Automation.Language.PipelineAst pipeline && pipeline.PipelineElements.IndexOf(commandAst) > 0;
                System.Management.Automation.Runspaces.Runspace? before = System.Management.Automation.Runspaces.Runspace.DefaultRunspace;
                System.Management.Automation.Runspaces.Runspace.DefaultRunspace = shell.Runspace;
                HashSet<string> bound;
                try
                {
                    System.Management.Automation.Language.StaticBindingResult result = System.Management.Automation.Language.StaticParameterBinder.BindCommand(commandAst, resolve: true);
                    bound = new HashSet<string>(result.BoundParameters.Values.Select(binding => binding.Parameter.Name), StringComparer.OrdinalIgnoreCase);
                }
                finally
                {
                    System.Management.Automation.Runspaces.Runspace.DefaultRunspace = before;
                }
                bool runs = info.ParameterSets.Any(set =>
                    bound.All(parameter => set.Parameters.Any(p => string.Equals(p.Name, parameter, StringComparison.OrdinalIgnoreCase)))
                    && set.Parameters.Where(p => p.IsMandatory).All(p => bound.Contains(p.Name) || (piped && (p.ValueFromPipeline || p.ValueFromPipelineByPropertyName))));
                if (!runs) problems.Add($"{commandAst.Extent.Text}: a mandatory parameter is left unbound");
            }
        }
        return problems;
    }

    [Theory]
    [MemberData(nameof(ModuleUnderTest.Names), MemberType = typeof(ModuleUnderTest))]
    public void The_help_syntax_has_one_line_per_parameter_set_that_says_what_the_engine_binds(string module)
    {
        // One syntax line per parameter set, each parameter with its position, whether it is required, and its pipeline
        // and wildcard support, as the engine binds it: a single line mixing every set (Get-ZbxHost -Name -Id -Filter,
        // all "required", every parameter "named") would mislead. Pinned against the engine's own metadata for every
        // exported command.
        using Shell shell = Shell.Open();

        Run run = shell.Invoke("""
            $common = [System.Management.Automation.Cmdlet]::CommonParameters + [System.Management.Automation.Cmdlet]::OptionalCommonParameters
            foreach ($c in Get-Command -Module $module -CommandType Cmdlet) {
                $help = Get-Help $c.Name -Full
                $items = @($help.syntax.syntaxItem)
                if ($items.Count -ne $c.ParameterSets.Count) { "$($c.Name): $($items.Count) syntax lines for $($c.ParameterSets.Count) parameter sets"; continue }
                foreach ($set in $c.ParameterSets) {
                    $own = @($set.Parameters | Where-Object Name -notin $common)
                    $names = ($own.Name | Sort-Object) -join ','
                    $item = $items | Where-Object { ((@($_.parameter) | Where-Object Name -notin $common).Name | Sort-Object) -join ',' -eq $names } | Select-Object -First 1
                    if (-not $item) { "$($c.Name)/$($set.Name): no syntax line lists $names"; continue }
                    foreach ($p in $own) {
                        $h = @($item.parameter) | Where-Object Name -eq $p.Name
                        $position = if ($p.Position -ge 0) { "$($p.Position)" } else { 'named' }
                        $pipeline = if ($p.ValueFromPipeline -and $p.ValueFromPipelineByPropertyName) { 'True (ByValue, ByPropertyName)' } elseif ($p.ValueFromPipeline) { 'True (ByValue)' } elseif ($p.ValueFromPipelineByPropertyName) { 'True (ByPropertyName)' } else { 'False' }
                        $globbing = [bool]($c.Parameters[$p.Name].Attributes | Where-Object { $_ -is [System.Management.Automation.SupportsWildcardsAttribute] })
                        if ("$($h.required)" -ne "$($p.IsMandatory)".ToLowerInvariant()) { "$($c.Name)/$($set.Name) -$($p.Name): required $($h.required), engine $($p.IsMandatory)" }
                        if ("$($h.position)" -ne $position) { "$($c.Name)/$($set.Name) -$($p.Name): position $($h.position), engine $position" }
                        if ("$($h.pipelineInput)" -ne $pipeline) { "$($c.Name)/$($set.Name) -$($p.Name): pipeline '$($h.pipelineInput)', engine '$pipeline'" }
                        if ("$($h.globbing)" -ne "$globbing".ToLowerInvariant()) { "$($c.Name)/$($set.Name) -$($p.Name): globbing $($h.globbing), engine $globbing" }
                    }
                }
            }
            """, new Dictionary<string, object?> { ["module"] = module });

        Assert.Empty(run.Errors);
        Assert.Empty(run.Output.Select(o => o.ToString()));
    }

    [Theory]
    [MemberData(nameof(ModuleUnderTest.Names), MemberType = typeof(ModuleUnderTest))]
    public void Get_Help_Online_opens_the_commands_generated_reference_page(string module)
    {
        ModuleUnderTest under = ModuleUnderTest.Named(module);
        string referenceDirectory = under.ReferenceDirectory;
        using Shell shell = Shell.Open();

        Run run = shell.Invoke("""
            Get-Command -Module $module -CommandType Cmdlet | ForEach-Object {
                [pscustomobject]@{ Name = $_.Name; Uri = [string](@((Get-Help $_.Name).relatedLinks.navigationLink)[0].uri) }
            }
            """, new Dictionary<string, object?> { ["module"] = module });

        Assert.Empty(run.Errors);
        var problems = new List<string>();
        foreach (PSObject link in run.Output)
        {
            var name = (string)link.Properties["Name"].Value;
            var uri = (string)link.Properties["Uri"].Value;
            if (!uri.EndsWith($"/reference/{under.Name}/{name}.html", StringComparison.Ordinal)) problems.Add($"{name}: {uri}");
            if (!File.Exists(Path.Combine(referenceDirectory, name + ".md"))) problems.Add($"{name}: no reference page");
        }
        Assert.Empty(problems);
        Assert.Equal(run.Output.Count + 1, Directory.EnumerateFiles(referenceDirectory, "*.md").Count());
    }

