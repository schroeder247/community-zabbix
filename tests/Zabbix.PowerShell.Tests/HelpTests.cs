    [Fact]
    public void Every_command_line_an_about_topic_shows_binds_to_real_commands_and_parameters()
    {
        // The indented code lines of every about topic, statically bound (StaticParameterBinder, the engine's own
        // binder without running anything): a renamed command or parameter fails here, not in a reader's shell.
        using Shell shell = Shell.Open();
        // A code block is set deeper than the prose around it (the topics indent prose 4 or 8 spaces, code 4 more) and
        // starts after a blank line; it runs while the lines stay at least that deep, and is parsed whole, so a
        // try { } catch { } over two lines is one script.
        var blocks = new List<string>();
        foreach (string file in AboutDirectories.SelectMany(directory => Directory.EnumerateFiles(directory, "about_Community.Zabbix*.help.txt")))
        {
            var block = new List<string>();
            int depth = -1, prose = 0;
            bool previousBlank = true;
            foreach (string line in File.ReadLines(file).Append(string.Empty))
            {
                int indent = line.Length - line.TrimStart(' ').Length;
                bool blank = line.Trim().Length == 0;
                if (depth >= 0 && !blank && indent >= depth)
                {
                    block.Add(line.Trim());
                    previousBlank = false;
                    continue;
                }
                if (block.Any(l => l.Contains("-Zbx", StringComparison.Ordinal))) blocks.Add(string.Join('\n', block));
                block.Clear();
                depth = -1;
                if (!blank)
                {
                    if (previousBlank && indent > prose && indent >= 8)
                    {
                        depth = indent;
                        block.Add(line.Trim());
                    }
                    else
                    {
                        prose = indent;
                    }
                }
                previousBlank = blank;
            }
        }

        Assert.NotEmpty(blocks);
        Assert.Empty(StaticBindingProblems(shell, blocks));
    }

