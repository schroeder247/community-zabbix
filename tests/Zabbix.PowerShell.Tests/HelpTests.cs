    [Fact]
    public void Get_Help_New_ZbxHostGroup_Full_shows_a_real_synopsis_description_parameters_and_an_example()
    {
        using Shell shell = Shell.Open();

        Run run = shell.Invoke("""
            $h = Get-Help New-ZbxHostGroup -Full
            [pscustomobject]@{
                Synopsis    = [string]$h.Synopsis
                Description = ($h.description | ForEach-Object Text) -join ' '
                Parameters  = @($h.parameters.parameter | ForEach-Object Name)
                Examples    = @($h.Examples.Example).Count
            }
            """);

        PSObject help = Assert.Single(run.Output);
        var synopsis = (string)help.Properties["Synopsis"].Value;
        var description = (string)help.Properties["Description"].Value;
        var parameters = ((object[])help.Properties["Parameters"].Value).Select(item => item is PSObject wrapped ? (string)wrapped.BaseObject : (string)item);
