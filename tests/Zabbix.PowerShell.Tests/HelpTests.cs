        }

        Assert.Empty(violations);
    }

    [Theory]
    [MemberData(nameof(ModuleUnderTest.Names), MemberType = typeof(ModuleUnderTest))]
    public void Every_exported_cmdlet_shows_a_synopsis_description_documented_parameters_and_an_example_through_Get_Help(string module)
    {
        using Shell shell = Shell.Open();

        Run run = shell.Invoke("""
            Get-Command -Module $module -CommandType Cmdlet | ForEach-Object {
                $h = Get-Help $_.Name -Full
                $liveParameters = @($_.Parameters.Keys | Where-Object { $_ -notin $common })
                $documentedParameters = @($h.parameters.parameter | ForEach-Object Name)
                [pscustomobject]@{
                    Name        = $_.Name
                    Synopsis    = [string]$h.Synopsis
                    HasExample  = @($h.Examples.Example).Count -gt 0
                    Undocumented = @($liveParameters | Where-Object { $_ -notin $documentedParameters })
                }
            }
            """, new Dictionary<string, object?> { ["common"] = CommonParameters, ["module"] = module });

        Assert.Empty(run.Errors);
        Assert.Equal(ModuleUnderTest.Named(module).Cmdlets.Count(), run.Output.Count);
        var violations = new List<string>();
        foreach (PSObject result in run.Output)
        {
            var name = (string)result.Properties["Name"].Value;
            var synopsis = ((string?)result.Properties["Synopsis"].Value ?? string.Empty).Trim();
            var hasExample = (bool)result.Properties["HasExample"].Value;
            var undocumented = (object[])result.Properties["Undocumented"].Value;

            if (synopsis.Length == 0 || synopsis.StartsWith(name, StringComparison.Ordinal)) violations.Add($"{name}: no real synopsis");
            if (!hasExample) violations.Add($"{name}: no example");
            foreach (object missing in undocumented) violations.Add($"{name}: -{missing} undocumented");
        }

        Assert.Empty(violations);
    }

    [Fact]
